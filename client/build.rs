use std::env;
use std::fs::File;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
     
     
    let dest = env::var("OUT_DIR").unwrap();
    let mut file = File::create(Path::new(&dest).join("bindings.rs")).unwrap();

     
    Registry::new(Api::Gl, (3, 3), Profile::Compatibility, Fallbacks::All, [])
        .write_bindings(GlobalGenerator, &mut file)
        .unwrap();

    if env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
        && env::var("PROFILE").as_deref() == Ok("release")
        && env::var_os("CARGO_FEATURE_DEVTEST").is_none()
    {
        println!("cargo:rustc-link-arg-cdylib=/DEBUG:NONE");
    }

    compile_jvmti_shim();
    compile_camera_bridge();
    generate_vanilla_textures();

    #[cfg(windows)]
    find_jvm_lib();

    #[cfg(target_os = "linux")]
    link_jvm_linux();
}

 
 
 
 
 
 
 
 
fn generate_vanilla_textures() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("assets").join("minecraft").join("textures");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    for folder in ["item", "block"] {
        let Ok(dir) = std::fs::read_dir(root.join(folder)) else {
            continue;
        };
        for entry in dir.flatten() {
            let path = entry.path();
            if path.extension().and_then(|extension| extension.to_str()) != Some("png") {
                continue;
            }
            let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) else {
                continue;
            };
            entries.push((format!("{folder}/{stem}"), path));
        }
    }
    if entries.is_empty() {
        panic!(
            "build.rs: no vanilla textures under {} — run `py client/tools/extract_vanilla_icons.py`",
            root.display()
        );
    }
    entries.sort();

    let mut source = String::from(
        "// @generated by build.rs from assets/minecraft/textures — do not edit.\n\
         /// Vanilla `item/…` and `block/…` textures, sorted by name.\n\
         pub(crate) static VANILLA_TEXTURES: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &entries {
        let path = path.display().to_string().replace('\\', "/");
        source.push_str(&format!("    ({name:?}, include_bytes!(\"{path}\")),\n"));
    }
    source.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("vanilla_textures.rs");
    std::fs::write(&out, source)
        .unwrap_or_else(|error| panic!("build.rs: could not write {}: {error}", out.display()));
}

 
 
